// Generates src/styles/tokens.css and src/lib/ds/palette.generated.ts
// from the colour bases measured out of "Full Design System (Community)" -> Foundation.jpg.
//
// Swatch strip rule (verified against pixel samples of the original):
//   Dark 10%  = base mixed 10% with black
//   Light 90% = base mixed 10% with white   (i.e. 90% base)
//   75 / 50 / 25 / 10 = base at that opacity over white
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const hexToRgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const rgbToHex = (rgb) =>
  "#" + rgb.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("").toUpperCase();
const mixWhite = (hex, alpha) => rgbToHex(hexToRgb(hex).map((v) => v * alpha + 255 * (1 - alpha)));
const mixBlack = (hex, alpha) => rgbToHex(hexToRgb(hex).map((v) => v * alpha));

const scale = (base) => ({
  base,
  dark: mixBlack(base, 0.9),
  light: mixWhite(base, 0.9),
  "75": mixWhite(base, 0.75),
  "50": mixWhite(base, 0.5),
  "25": mixWhite(base, 0.25),
  "10": mixWhite(base, 0.1),
});

// Foundation > Color Scheme (brand)
const brand = [
  { key: "primary", name: "Primary | Sky Blue", hex: "#517CFF", usage: "Primary actions, links, focus" },
  { key: "secondary", name: "Secondary | Purple", hex: "#7E5BEF", usage: "Secondary accents, editing state" },
  { key: "support", name: "Support | MC Pink", hex: "#FF49DA", usage: "Support / highlight accents" },
  { key: "gray", name: "Gray | Ocean Gray", hex: "#9AA5B5", usage: "Neutrals, borders, muted UI" },
];

// Foundation > Alerts (semantic)
// NOTE: the source artboard prints "#3366FF" on the Warning swatch (copy/paste slip);
// the swatch itself is #FFB020, which is what is used here.
const semantic = [
  { key: "success", name: "Success | Grass Green", hex: "#13CE66", usage: "Success alerts and confirmations" },
  { key: "info", name: "Info | News Blue", hex: "#3366FF", usage: "Informational alerts" },
  { key: "warning", name: "Warning | Warn", hex: "#FFB020", usage: "Warnings and caution states" },
  { key: "danger", name: "Danger | Error", hex: "#FF000D", usage: "Errors and destructive actions" },
];

// UI kit palette sampled from the "Style Guide" / "Frame 1" PNG exports
const kit = [
  { key: "kit-blue", name: "Kit Blue", hex: "#2169E8", usage: "Kit primary buttons, checks, charts" },
  { key: "kit-green", name: "Kit Green", hex: "#41A15A", usage: "Kit success banner, progress" },
  { key: "kit-orange", name: "Kit Orange", hex: "#E57439", usage: "Kit warning banner, progress" },
  { key: "kit-red", name: "Kit Red", hex: "#C94848", usage: "Kit error banner" },
  { key: "kit-navy", name: "Kit Navy", hex: "#14102A", usage: "Dark surfaces: toasts, popovers, calendars" },
  { key: "kit-gray", name: "Kit Gray", hex: "#C5CACD", usage: "Disabled / neutral buttons" },
  { key: "kit-gray-soft", name: "Kit Gray Soft", hex: "#E6E7EA", usage: "Dividers, tracks" },
  { key: "kit-gray-faint", name: "Kit Gray Faint", hex: "#F4F4F7", usage: "Panels, table backgrounds" },
];

// Component-level colours measured from Components.jpg
const ui = {
  ink: "#0F142A", // section titles
  "ink-body": "#5B5D72", // nav links, secondary text
  "ink-muted": "#7F8190", // subtitles, labels
  placeholder: "#B0B3BC",
  line: "#E4E4E4", // input border
  "line-soft": "#E9E9F0", // section divider
  disabled: "#F8F8F8",
  "nav-green": "#0ABC5C",
  "nav-blue": "#203DE2",
  "nav-blue-tint": "#EDF0FF",
  "avatar-pink": "#E197A4",
  "avatar-empty": "#E5E5E5",
  "avatar-initial-bg": "#DDF2EB",
  "avatar-initial-fg": "#348366",
  "badge-edit": "#7B5CF5",
  "badge-ok": "#1F8B24",
  "badge-off": "#867D7E",
  "badge-error": "#F23B3B",
  "field-focus": "#5F75ED",
  "field-success": "#52BC94",
  "alert-success-bg": "#E0F2D8",
  "alert-success-accent": "#84C441",
  "alert-success-title": "#3E8A38",
  "alert-success-text": "#425843",
  "alert-info-bg": "#EAF0FE",
  "alert-info-accent": "#4574FE",
  "alert-warning-bg": "#FFF7EA",
  "alert-warning-accent": "#FFAE1F",
  "alert-danger-bg": "#FFE5E8",
  "alert-danger-accent": "#FF000D",
};

const lines = [];
lines.push("/* AUTO-GENERATED by scripts/gen-tokens.mjs. Do not edit by hand. */");
lines.push("@theme {");
for (const group of [brand, semantic]) {
  for (const c of group) {
    const s = scale(c.hex);
    lines.push(`  --color-${c.key}: ${s.base};`);
    lines.push(`  --color-${c.key}-dark: ${s.dark};`);
    lines.push(`  --color-${c.key}-light: ${s.light};`);
    for (const step of ["75", "50", "25", "10"]) lines.push(`  --color-${c.key}-${step}: ${s[step]};`);
  }
}
for (const c of kit) lines.push(`  --color-${c.key}: ${c.hex};`);
for (const [k, v] of Object.entries(ui)) lines.push(`  --color-${k}: ${v};`);
lines.push("}");
lines.push("");

mkdirSync(resolve(root, "src/styles"), { recursive: true });
writeFileSync(resolve(root, "src/styles/tokens.css"), lines.join("\n"));

const out = `// AUTO-GENERATED by scripts/gen-tokens.mjs. Do not edit by hand.
export type Swatch = { key: string; name: string; hex: string; usage: string; scale: Record<"base" | "dark" | "light" | "75" | "50" | "25" | "10", string> };

export const brandPalette: Swatch[] = ${JSON.stringify(brand.map((c) => ({ ...c, scale: scale(c.hex) })), null, 2)};

export const semanticPalette: Swatch[] = ${JSON.stringify(semantic.map((c) => ({ ...c, scale: scale(c.hex) })), null, 2)};

export const kitPalette: { key: string; name: string; hex: string; usage: string }[] = ${JSON.stringify(kit, null, 2)};

export const uiColors: Record<string, string> = ${JSON.stringify(ui, null, 2)};
`;
mkdirSync(resolve(root, "src/lib/ds"), { recursive: true });
writeFileSync(resolve(root, "src/lib/ds/palette.generated.ts"), out);
console.log("tokens written");
